def cleanup_memory():
    """Forces garbage collection and GPU memory release."""
    gc.collect()
    if IS_CUPY_BACKEND:
        xp.get_default_memory_pool().free_all_blocks()


def scatter_maximum_1d(out: Array, idx: Array, vals: Array) -> None:
    """
    1D segmented max scatter: ``out[idx[i]] = max(out[idx[i]], vals[i])``.
    Uses `cupyx.scatter_max` on GPU and `numpy.maximum.at` semantics on CPU.
    Eg:
        out = [0, 0, 0]
        idx = [0, 1, 0, 2, 1]
        vals = [1, 2, 3, 4, 0]
        scatter_maximum_1d(out, idx, vals)
        # out is now [3, 2, 4]

    Args:
        out: (K,) output array updated in-place.
        idx: (N,) integer indices in [0, K).
        vals: (N,) values to reduce via max per index.
    """
    if IS_CUPY_BACKEND:
        cupy_scatter_max(out, idx, vals)
    else:
        xp.maximum.at(out, idx, vals)


def flatten_function_array(F: Array) -> Array:
    """
    Normalize function values to a flat (N,) array.
    The user-provided `f_fn` may return either (N,), (N,1), or something reshapeable
    to (N,).

    Args:
        F: Array-like of function values.

    Returns:
        F_flat: (N,) array.
    """
    return F.reshape((-1,))


def flatten_gradient_array(G: Array) -> Array:
    """
    Normalize gradients to a dense (N, d) array.
    Accepts either:
      - (N, d) gradients, or
      - (N, 1, d) gradients (common when batching Jacobians).

    Args:
        G: Array-like gradients.

    Returns:
        G2: (N, d) gradient array.
    """
    if G.ndim == 3 and G.shape[1] == 1:
        return G[:, 0, :]
    if G.ndim == 2:
        return G
    raise ValueError(f"Unexpected gradient shape {G.shape}; expected (N,d) or (N,1,d).")


def compute_label_segments(sorted_labels: Array) -> tuple[Array, Array, Array]:
    """Compute segmentation metadata for a label-sorted 1D label array.

    Args:
        sorted_labels: (N,) labels sorted in nondecreasing order.

    Returns:
        uniq: (K,) unique label values (ascending).
        starts: (K,) start indices of each label-run in `sorted_labels`.
        counts: (K,) run lengths.
    """
    uniq, starts, counts = xp.unique(
        sorted_labels, return_index=True, return_counts=True
    )
    return uniq, starts, counts


def fill_synthetic_points_chunked(
    X_out: Array,
    labels_out: Array,
    X_pool: Array,
    idx_sorted: Array,
    starts: Array,
    counts: Array,
    uniq_labels: Array,
    synth_needs: Array,
    SEED: int,
    level: int,
    CHUNK_SIZE: int = 1_000_000,
) -> None:
    """
    Fill `X_out` and `labels_out` with synthetic points generated by random
    convex combinations of points from `X_pool`.

    For each cluster k, `synth_needs[k]` synthetic points are generated by
    randomly selecting pairs of points from that cluster and forming convex
    combinations.

    Args:
        X_out: (M, d) output array to fill with synthetic points.
        labels_out: (M,) output array to fill with cluster labels.
        X_pool: (N, d) pool of existing points.
        idx_sorted: (N_active,) or slice of active point indices in `X_pool`,
            sorted by cluster label.
        starts: (K,) start indices of each cluster in `idx_sorted`.
        counts: (K,) number of points in each cluster.
        uniq_labels: (K,) unique cluster labels.
        synth_needs: (K,) number of synthetic points needed per cluster.
        SEED: base random seed for reproducibility.
        level: current adaptive clustering level (used to vary RNG seed).
        CHUNK_SIZE: number of synthetic points to generate per chunk.
    """
    total_synth = int(X_out.shape[0])
    rng = xp.random.default_rng(SEED + level)

    # Map each synthetic point to its cluster
    k_synth_all = repeats(xp.arange(int(synth_needs.shape[0])), synth_needs)
    labels_out[:] = uniq_labels[k_synth_all]

    for chunk_start in range(0, total_synth, CHUNK_SIZE):
        # Chunk boundaries
        chunk_end = min(total_synth, chunk_start + CHUNK_SIZE)
        curr_size = chunk_end - chunk_start

        # Generate synthetic points in this chunk
        k_chunk = k_synth_all[chunk_start:chunk_end]
        m = counts[k_chunk]
        s0 = starts[k_chunk]

        # i,j indices for convex combinations
        rand_i = rng.random(curr_size)
        i = (xp.floor(rand_i * m)).astype(xp.int64)

        rand_j = rng.random(curr_size)
        j = (xp.floor(rand_j * (m - 1))).astype(xp.int64)
        j = j + (j >= i)

        # Map to global indices in X_pool
        if isinstance(idx_sorted, slice):
            global_i = (idx_sorted.start or 0) + s0 + i
            global_j = (idx_sorted.start or 0) + s0 + j
        else:
            global_i = idx_sorted[s0 + i]
            global_j = idx_sorted[s0 + j]

        # Generate random convex combinations
        a = rng.random((curr_size, 1)).astype(X_pool.dtype)
        p1 = X_pool[global_i]
        p2 = X_pool[global_j]
        X_out[chunk_start:chunk_end] = a * p1 + (1.0 - a) * p2


def calculate_Q(
    DeltaX: Array,
    starts: Array,
    counts: Array,
    K: int,
    *,
    Q_SHRINK: float = 0.0,
) -> tuple[Array, Array]:
    """
    Calculate the local metric tensor Q for each cluster based on point deviations.
    This constructs, for each lcuster k, a PSD matrix Q_k defining an ellipsoid:
        {x : (x - mu_k)^T Q_k (x - mu_k) <= 1, x in cluster k}.
    The construction uses covariance shrinkage and rescales to ensure all points
    in the cluster lie within the ellipsoid.

    Args:
        DeltaX: (N, d) deviations of points from their cluster centroids.
        starts: (K,) start indices of each cluster in DeltaX.
        counts: (K,) number of points in each cluster.
        K: number of clusters.
        Q_EPS_AXIS: minimum axis length to prevent degenerate ellipsoids.
        Q_SHRINK: shrinkage factor for covariance estimation (Ledoit-Wolf shrinkage).

    Returns:
        Q: (K, d, d) local metric tensors for each cluster.
        Cov: (K, d, d) covariance matrices for each cluster.
    """
    N, d = DeltaX.shape
    dtype = DeltaX.dtype

    # Accumulate Covariance
    Cov = xp.empty((K, d, d), dtype=dtype)
    for i in range(d):
        dxi = DeltaX[:, i]
        for j in range(i, d):
            # sum(x_i * x_j) for each cluster
            val = xp.add.reduceat(dxi * DeltaX[:, j], starts)
            Cov[:, i, j] = val
            if i != j:
                Cov[:, j, i] = val
    Cov = 0.5 * (Cov + Cov.transpose(0, 2, 1))  # (K, d, d)

    if Q_SHRINK > 0.0:
        # Apply Ledoit-Wolf shrinkage
        d_int = int(Cov.shape[1])
        tr = xp.trace(Cov, axis1=1, axis2=2)
        scale_tr = tr / max(d_int, 1)
        I = xp.eye(d_int, dtype=Cov.dtype)[None, :, :]
        Cov = (1.0 - Q_SHRINK) * Cov + Q_SHRINK * (scale_tr[:, None, None] * I)
        Cov = 0.5 * (Cov + Cov.transpose(0, 2, 1))

        # Eigendecomposition
        Lambda, U = xp.linalg.eigh(Cov)

        # Invert eigenvalues to get the shape matrix diagonal
        # Since Cov is shrunk/PSD, Lambda > 0 usually, but we clamp for safety
        Lambda = xp.maximum(Lambda, TINY_EPS)
        Lambda_inv = 1.0 / Lambda  # (K, d)

        # Calculate Projections
        # Computes p = U^T x without creating (N, d, d)
        map_n_to_k = repeats(xp.arange(K), counts)
        proj = xp.empty((N, d), dtype=dtype)

        for j in range(d):
            accum = xp.zeros(N, dtype=dtype)
            for m in range(d):
                # Dot product of point x with j-th eigenvector u_j
                # U[k, m, j] is the m-th component of the j-th eigenvector for cluster k
                u_elem = U[map_n_to_k, m, j]
                accum += u_elem * DeltaX[:, m]
            proj[:, j] = accum

        # Calculate Scaled Covariance Size
        # dist^2 = sum(proj_j^2 / lambda_j)
        L_inv_points = Lambda_inv[map_n_to_k]  # (N, d)
        dist_sq = xp.sum((proj * proj) * L_inv_points, axis=1)  # (N,)

        # Find max distance per cluster
        max_dist_sq = xp.zeros((K,), dtype=proj.dtype)
        scatter_maximum_1d(max_dist_sq, map_n_to_k, dist_sq)

        # Prevent divide-by-zero for single-point clusters
        max_dist_sq = xp.maximum(max_dist_sq, TINY_EPS)

        # Scale factor alpha = 1 / max_dist
        scale = 1.0 / max_dist_sq  # (K,)

        # Construct Q
        # Q = scale * (U Lambda_inv U^T)
        # effectively new eigenvalues are scale / Lambda
        final_D = scale[:, None] * Lambda_inv  # (K, d)

        # Reconstruct Q matrix
        Q = (U * final_D[:, None, :]) @ U.transpose(0, 2, 1)
    else:
        # No shrinkage; use axis-aligned ellipsoids

        # Eigendecomposition
        _, U = xp.linalg.eigh(Cov)
        map_n_to_k = repeats(xp.arange(K), counts)

        # Calculate Projections
        proj = xp.empty((N, d), dtype=dtype)
        for j in range(d):
            accum = xp.zeros(N, dtype=dtype)
            for m in range(d):
                u_elem = U[map_n_to_k, m, j]
                accum += u_elem * DeltaX[:, m]
            proj[:, j] = accum

        proj_abs = xp.abs(proj)

        # Find max absolute projection per axis per cluster
        d_axes = xp.zeros((K, proj_abs.shape[1]), dtype=proj_abs.dtype)
        scatter_maximum_1d(d_axes, map_n_to_k, proj_abs)
        d_axes = xp.maximum(d_axes, TINY_EPS)
        Dinv2 = 1.0 / (d_axes * d_axes)

        # Construct Q
        # Q = U Dinv2 U^T
        Q = (U * Dinv2[:, None, :]) @ U.transpose(0, 2, 1)

    return 0.5 * (Q + Q.transpose(0, 2, 1)), Cov


def estimate_hessian_sqrt_symmetric(
    DeltaX: Array,
    DeltaG: Array,
    starts: Array,
) -> Array:
    """
    Symmetric Hessian estimation via least-squares fit (Sylvester solve in eigenbasis),
    followed by |H|^{1/2} computation via eigendecomposition.
    Solve: H C + C H = S,  where
        C = sum_i (Δx_i Δx_i^T)
        S = sum_i (Δx_i Δg_i^T + Δg_i Δx_i^T)

    Args:
        DeltaX: (N, d) deviations of points from their cluster centroids.
        DeltaG: (N, d) deviations of gradients from their cluster gradients.
        starts: (K,) start indices of each cluster in DeltaX/DeltaG.

    Returns:
        M: (K, d, d) estimated |H|^{1/2} matrices for each cluster.
    """
    d = DeltaX.shape[1]
    K = starts.shape[0]

    # Initialize accumulators
    C = xp.empty((K, d, d), dtype=DeltaX.dtype)
    E = xp.empty((K, d, d), dtype=DeltaX.dtype)

    # Accumulate C and E
    for i in range(d):
        dxi = DeltaX[:, i]
        for j in range(i, d):
            val = xp.add.reduceat(dxi * DeltaX[:, j], starts)
            C[:, i, j] = val
            if i != j:
                C[:, j, i] = val

    # Accumulate E
    for i in range(d):
        dxi = DeltaX[:, i]
        for j in range(d):
            E[:, i, j] = xp.add.reduceat(dxi * DeltaG[:, j], starts)

    C = 0.5 * (C + C.transpose(0, 2, 1))  # (K, d, d)
    S = E + E.transpose(0, 2, 1)  # (K, d, d)

    dvals, U = xp.linalg.eigh(C)
    dvals = xp.maximum(dvals, TINY_EPS)  # (K, d)

    # Solve Sylvester equation in eigenbasis
    Gtilde = U.transpose(0, 2, 1) @ S @ U  # (K, d, d)
    denom = dvals[:, :, None] + dvals[:, None, :]  # (K, d, d)
    F = Gtilde / denom  # (K, d, d)

    # Compute |H|^{1/2}
    h_eigvals, V = xp.linalg.eigh(F)
    Z = U @ V  # (K, d, d)
    w_abs_sqrt = xp.sqrt(xp.abs(h_eigvals))  # (K, d)

    M = (Z * w_abs_sqrt[:, None, :]) @ Z.transpose(0, 2, 1)  # (K, d, d)
    return 0.5 * (M + M.transpose(0, 2, 1))


def get_dominant_eigenvector(Cov: Array) -> Array:
    """Dominant eigenvector of symmetric covariance matrices.

    Args:
        Cov: (K, d, d) symmetric matrices.

    Returns:
        v: (K, d) top eigenvector per matrix.
    """
    # w asc => last is largest
    w, V = xp.linalg.eigh(Cov)
    return V[:, :, -1]


def compute_median_split_decision(
    scores: Array,
    cluster_id: Array,
    starts: Array,
    counts: Array,
) -> Array:
    """
    Compute per-cluster median split decisions for a packed (clustered) score vector.

    Given per-point scores `scores` and a per-point cluster id `cluster_id` (local ids
    like 0..K-1), return a boolean decision:
        decision[i] = scores[i] >= median(scores within that cluster).

    Implementation note:
        This uses a two-stage argsort (by score, then by cluster id) to obtain scores
        sorted *within clusters* without explicit Python loops.
    """
    N = int(scores.shape[0])
    if N == 0:
        return scores >= 0

    idx_by_score = xp.argsort(scores)
    cid_by_score = cluster_id[idx_by_score]
    idx_group = xp.argsort(cid_by_score)
    order = idx_by_score[idx_group]
    scores_sorted = scores[order]

    i0 = starts + (counts - 1) // 2
    i1 = starts + counts // 2
    median = 0.5 * (scores_sorted[i0] + scores_sorted[i1])  # (K,)
    return scores >= median[cluster_id]


def allocate_output_buffers(
    MAX_CLUSTERS_EST: int, d: int, dtype: Any
) -> tuple[dict, int]:
    """Allocate output buffers for finalized clusters.

    Args:
        MAX_CLUSTERS_EST: initial capacity estimate for finalized clusters.
        d: dimensionality of the input space.
        dtype: floating dtype for outputs.

    Returns:
        buffers: dict of arrays sized to `cap`.
        cap: allocated capacity (number of clusters).
    """
    cap = max(1, int(MAX_CLUSTERS_EST))
    buffers = {
        "centroids": np.empty((cap, d), dtype=dtype),
        "f": np.empty((cap,), dtype=dtype),
        "g": np.empty((cap, d), dtype=dtype),
        "Q": np.empty((cap, d, d), dtype=dtype),
        "E_rel": np.empty((cap,), dtype=dtype),
        "counts": np.empty((cap,), dtype=np.int64),
    }
    return buffers, cap


def adjust_buffer_capacity(
    buffers: dict, current_count: int, current_cap: int, required_total: int
) -> tuple[dict, int]:
    """Grow output buffers if the finalized cluster count exceeds current capacity.

    Args:
        buffers: current output buffers.
        current_count: number of clusters currently written.
        current_cap: current capacity.
        required_total: required capacity after the next write.

    Returns:
        new_buffers: potentially reallocated buffers.
        new_cap: updated capacity.
    """
    if required_total <= current_cap:
        return buffers, current_cap

    d = int(buffers["centroids"].shape[1])
    new_cap = max(required_total, max(1, current_cap) * 2)
    dtype = buffers["centroids"].dtype

    logger.warning(
        f"Resizing output buffers (CPU): {current_cap:,} -> {new_cap:,} clusters"
    )

    new_buffers = {
        "centroids": np.empty((new_cap, d), dtype=dtype),
        "f": np.empty((new_cap,), dtype=dtype),
        "g": np.empty((new_cap, d), dtype=dtype),
        "Q": np.empty((new_cap, d, d), dtype=dtype),
        "E_rel": np.empty((new_cap,), dtype=dtype),
        "counts": np.empty((new_cap,), dtype=np.int64),
    }

    if current_count > 0:
        for k in new_buffers:
            new_buffers[k][:current_count] = buffers[k][:current_count]

    # Deallocate old buffers
    del buffers
    return new_buffers, int(new_cap)
